import type { Metadata } from 'next';
import { Geist, Geist_Mono } from 'next/font/google';
import { config } from '@optimizely/cms-sdk';
import { initForms } from '@optimizely/cms-sdk/react/server';

import './globals.css';
import { initRegistry } from '../../.optimizely/registry';
import BlankSection from '@/components/base/BlankSection';
import FormContainer from '@/components/forms/FormContainer';
import FormChoice from '@/components/forms/FormChoice';
import FormInput from '@/components/forms/FormInput';
import FormNumber from '@/components/forms/FormNumber';
import FormRange from '@/components/forms/FormRange';
import FormReset from '@/components/forms/FormReset';
import FormSelection from '@/components/forms/FormSelection';
import FormSubmit from '@/components/forms/FormSubmit';
import FormTextarea from '@/components/forms/FormTextarea';
import FormUrl from '@/components/forms/FormUrl';

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

// Configure Optimizely Graph client
config({
  apiKey: process.env.OPTIMIZELY_GRAPH_SINGLE_KEY!,
  graphUrl: process.env.OPTIMIZELY_GRAPH_GATEWAY,
  fragment: {
    richTextFormat: 'json',
  },
  query: {
    host: process.env.APPLICATION_HOST,
  },
});

// BlankSection has no content type of its own, so it is registered here
initRegistry({ BlankSection });

initForms({
  container: FormContainer,
  choice: FormChoice,
  number: FormNumber,
  range: FormRange,
  reset: FormReset,
  selection: FormSelection,
  submit: FormSubmit,
  textbox: FormInput,
  textarea: FormTextarea,
  url: FormUrl,
});

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang='en'>
      <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
        {children}
      </body>
    </html>
  );
}