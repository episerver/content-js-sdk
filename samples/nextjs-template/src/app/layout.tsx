import React from 'react';

import { Bodoni_Moda, Inter } from 'next/font/google';
import './globals.css';
import { config } from '@optimizely/cms-sdk';
import { initRegistry } from '../../.optimizely/registry';
import BlankExperience from '@/components/BlankExperience';
import BlankSection from '@/components/BlankSection';

config({
  apiKey: process.env.OPTIMIZELY_GRAPH_SINGLE_KEY || 'your api key here',
  graphUrl: process.env.OPTIMIZELY_GRAPH_GATEWAY,
  fragment: {
    // These samples render body.html via dangerouslySetInnerHTML and body.json via RichText; the SDK default is 'json'.
    richTextFormat: 'both',
  },
});

// Generated by opti-typegen. These two have no content type of their own, so they are passed in.
initRegistry({ BlankExperience, BlankSection });

const serifFont = Bodoni_Moda({
  variable: '--font-serif',
  subsets: ['latin'],
});

const sansFont = Inter({
  variable: '--font-sans',
  subsets: ['latin'],
});

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang='en' className={[serifFont.variable, sansFont.variable].join(' ')}>
      <body>{children}</body>
    </html>
  );
}